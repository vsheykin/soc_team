def table(data, widths, header=True, align_center_cols=None):
    out = []
    for ri, row in enumerate(data):
        orow = []
        for ci, cell in enumerate(row):
            if ri == 0 and header:
                p = Paragraph(str(cell), ParagraphStyle("th", fontName="DejaVu-Bold",
                          fontSize=9, leading=12, textColor=colors.white, alignment=TA_CENTER))
            else:
                pstyle = st_body
                if align_center_cols and ci in align_center_cols:
                    pstyle = ParagraphStyle("tc", parent=st_body, alignment=TA_CENTER)
                p = Paragraph(str(cell), pstyle)
            orow.append(p)
        out.append(orow)
    t = Table(out, colWidths=widths, repeatRows=1 if header else 0)
    style = [("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#B7C4D4")),
             ("VALIGN", (0, 0), (-1, -1), "TOP"),
             ("LEFTPADDING", (0, 0), (-1, -1), 5), ("RIGHTPADDING", (0, 0), (-1, -1), 5),
             ("TOPPADDING", (0, 0), (-1, -1), 4), ("BOTTOMPADDING", (0, 0), (-1, -1), 4)]
    if header:
        style.append(("BACKGROUND", (0, 0), (-1, 0), ACCENT))
        style.append(("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, GREY]))
    t.setStyle(TableStyle(style))
    return t

